// The token radar's model, version radar-2: one snapshot of the protocol universe in,
// one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and
// every other rankable pre-token protocol in the snapshot: the early rows the radar exists to
// find. A protocol is pre-token when its index entry records no token (no market cap, no
// CoinGecko id, no symbol); the snapshot's live-token protocols are kept apart and shown as
// the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, through comparable tokenized
// protocols in the same category:
//
//   peerMultiple(category) = the median market-cap / TVL of the tokenized protocols in that
//                            category, shrunk toward the whole-snapshot median with a prior
//                            weight of PEER_SHRINK_K, clamped to [PEER_FLOOR, PEER_CAP]
//   base                   = tvl_usd x peerMultiple(category)
//   growth                 = clamp(change_7d, -60, 120) per cent
//   growthMult             = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity               = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied                = max(1, round(base x growthMult x maturity))
//
// A category with few tokenized peers leans on the global median; a category with none uses
// it outright. No protocol name is ever special-cased: the same function scores every row,
// and the peer table itself is computed from the snapshot at run time.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the page recomputes them. */
